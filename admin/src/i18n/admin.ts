export function getAdminTranslations(locale: SiteLocale): AdminTranslations {
  return locale === 'kk' ? adminKk : adminRu;
}

export function useAdminTranslation(): AdminTranslations {
  const { locale } = useLocale();
  return getAdminTranslations(locale);
}

export function adminErrorMessage(error: unknown, locale: SiteLocale = 'ru'): string {
  const code = error instanceof ApiError ? error.code : 'UNKNOWN_ERROR';
  const dict = getAdminTranslations(locale).errors;
  return (dict as Record<string, string>)[code] ?? dict.UNKNOWN_ERROR;
}
